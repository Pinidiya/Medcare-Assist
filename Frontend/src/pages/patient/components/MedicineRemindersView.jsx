import { useState, useEffect } from 'react';
import { 
  Bell, X, CheckCircle, XCircle, Info, Lightbulb, ExternalLink
} from 'lucide-react';
import patientBannerImg from '../../../assets/patient banner.png';

const API = import.meta.env.VITE_API_BASE_URL;

function Toast({ message, type = 'success', onClose }) {
  useEffect(() => {
    const t = setTimeout(onClose, 4000);
    return () => clearTimeout(t);
  }, [onClose]);

  const colors = type === 'success'
    ? 'bg-green-600 text-white'
    : type === 'error'
      ? 'bg-red-600 text-white'
      : 'bg-blue-600 text-white';

  return (
    <div className={`fixed top-6 right-6 z-[100] flex items-center gap-3 ${colors} px-5 py-3.5 rounded-xl shadow-2xl animate-fadeIn`}>
      {type === 'success' && <CheckCircle className="w-5 h-5" />}
      {type === 'error' && <XCircle className="w-5 h-5" />}
      {type === 'info' && <Info className="w-5 h-5" />}
      <p className="text-sm font-semibold">{message}</p>
      <button onClick={onClose} className="ml-2 opacity-70 hover:opacity-100">
        <X className="w-4 h-4" />
      </button>
    </div>
  );
}

export default function MedicineRemindersView() {

  const [toast, setToast] = useState(null);

  // Manual generator state
  const [manualFrequency, setManualFrequency] = useState('1');
  const [manualHour, setManualHour] = useState('08');
  const [manualMinute, setManualMinute] = useState('00');
  const [manualAmpm, setManualAmpm] = useState('AM');
  const [manualEndDate, setManualEndDate] = useState('');

  const generateCalendarUrl = (med) => {
    const text = encodeURIComponent(`Take Medicine: ${med.medicine_name}`);
    const details = encodeURIComponent(`Instructions: ${med.dosage_instructions}`);
    
    // Create local date object from MySQL datetime (which is usually local time in this context)
    const localDate = new Date(med.next_dose_datetime.replace(' ', 'T'));
    
    // Format to YYYYMMDDTHHMMSSZ (Google Calendar format)
    const toGoogleFormat = (date) => {
      return date.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
    };

    const startStr = toGoogleFormat(localDate);
    
    // End time 15 mins later
    const endLocalDate = new Date(localDate.getTime() + 15 * 60000);
    const endStr = toGoogleFormat(endLocalDate);

    return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${text}&details=${details}&dates=${startStr}/${endStr}`;
  };

  const addToGoogleCalendarApi = () => {
    try {
      const client = window.google.accounts.oauth2.initTokenClient({
        client_id: '292851178945-7p5gg1t37e3phgatjsob29ocok61nlmc.apps.googleusercontent.com',
        scope: 'https://www.googleapis.com/auth/calendar.events',
        callback: (tokenResponse) => {
          if (tokenResponse && tokenResponse.access_token) {
            createEventWithToken(tokenResponse.access_token);
          } else {
            setToast({ message: 'Google authentication failed', type: 'error' });
          }
        },
      });
      client.requestAccessToken();
    } catch (error) {
      console.error(error);
      setToast({ message: 'Google API is not loaded yet. Please wait a moment or refresh.', type: 'error' });
    }
  };

  const createEventWithToken = async (accessToken) => {
    let hour24 = parseInt(manualHour);
    if (manualAmpm === 'PM' && hour24 !== 12) hour24 += 12;
    if (manualAmpm === 'AM' && hour24 === 12) hour24 = 0;

    const today = new Date();
    const startDate = new Date(today.getFullYear(), today.getMonth(), today.getDate(), hour24, parseInt(manualMinute));
    const endDate = new Date(startDate.getTime() + 15 * 60000);

    const freqInt = parseInt(manualFrequency);
    let rrule = '';
    if (freqInt === 1) rrule = 'RRULE:FREQ=DAILY;INTERVAL=1';
    else if (freqInt === 2) rrule = 'RRULE:FREQ=HOURLY;INTERVAL=12';
    else if (freqInt === 3) rrule = 'RRULE:FREQ=HOURLY;INTERVAL=8';
    else if (freqInt === 4) rrule = 'RRULE:FREQ=HOURLY;INTERVAL=6';

    if (manualEndDate) {
      const endD = new Date(manualEndDate + 'T23:59:59Z');
      const toICSUTC = (date) => date.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
      rrule += `;UNTIL=${toICSUTC(endD)}`;
    }

    const toLocalISOString = (d) => {
      const pad = (n) => n.toString().padStart(2, '0');
      return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
    };

    const event = {
      summary: 'Take Medicine - MedCare Reminder',
      description: 'Time to take your medicine! Automatically generated by MedCare Assist.',
      start: {
        dateTime: toLocalISOString(startDate),
        timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone || 'Asia/Colombo'
      },
      end: {
        dateTime: toLocalISOString(endDate),
        timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone || 'Asia/Colombo'
      },
      recurrence: [rrule],
      reminders: {
        useDefault: false,
        overrides: [
          { method: 'popup', minutes: 0 },
          { method: 'popup', minutes: 10 }
        ]
      }
    };

    try {
      const response = await fetch('https://www.googleapis.com/calendar/v3/calendars/primary/events', {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${accessToken}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(event)
      });
      const data = await response.json();
      if (response.ok) {
         setToast({ message: 'Saved successfully to your Google Calendar! Alerts will sync to all devices.', type: 'success' });
      } else {
         setToast({ message: data.error?.message || 'Failed to save to Google Calendar', type: 'error' });
      }
    } catch (error) {
       setToast({ message: 'Network error communicating with Google', type: 'error' });
    }
  };

  return (
    <div className="space-y-6 animate-fadeIn">
      {toast && <Toast message={toast.message} type={toast.type} onClose={() => setToast(null)} />}
      {/* Header */}
      <div className="bg-[#f0f5fa] rounded-3xl overflow-hidden relative shadow-sm border border-blue-100/50 flex flex-col md:flex-row items-stretch justify-between min-h-[160px]">
        <div className="p-5 md:p-6 flex-1 w-full md:pr-0 z-10 flex flex-col justify-center">
          <div className="flex items-center gap-3 mb-1">
            <div className="w-8 h-8 bg-blue-500 rounded-lg flex items-center justify-center shadow-sm">
              <Bell className="w-5 h-5 text-white" />
            </div>
            <h2 className="text-lg font-extrabold text-[#1e293b]">Medicine Reminders</h2>
          </div>
          <p className="text-gray-500 text-xs mb-4 max-w-md">
            Directly connect and save reminders to your Google Calendar API.
          </p>
        </div>
        <div className="w-full md:w-[35%] h-40 md:h-[220px] absolute md:relative right-0 bottom-0 pointer-events-none flex justify-end">
          <img src={patientBannerImg} alt="Medicine Reminders" className="h-full object-cover md:object-contain object-right w-full opacity-30 md:opacity-100" style={{ maskImage: 'linear-gradient(to right, transparent 0%, black 20%)', WebkitMaskImage: 'linear-gradient(to right, transparent 0%, black 20%)' }} />
        </div>
      </div>

      {/* Smart Medicine Reminder Generator */}
      <div className="bg-white rounded-2xl shadow-sm border border-gray-100 overflow-hidden mt-6">
        <div className="px-6 py-5 border-b border-gray-100">
          <h3 className="font-bold text-gray-900 flex items-center gap-2 text-lg">
            <Lightbulb className="w-5 h-5 text-blue-500" /> Smart Reminder Generator
          </h3>
          <p className="text-sm text-gray-500 mt-1">Set your schedule and instantly push an alarm to your Google Calendar.</p>
        </div>
        <div className="p-6 space-y-5">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">Frequency <span className="text-red-500">*</span></label>
              <select
                value={manualFrequency}
                onChange={(e) => setManualFrequency(e.target.value)}
                className="w-full px-4 py-3 bg-gray-50 border border-gray-200 rounded-xl focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all text-sm font-medium appearance-none"
              >
                <option value="1">1 time a day (Every 24 hours)</option>
                <option value="2">2 times a day (Every 12 hours)</option>
                <option value="3">3 times a day (Every 8 hours)</option>
                <option value="4">4 times a day (Every 6 hours)</option>
              </select>
            </div>
            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">Start Time (First Dose) <span className="text-red-500">*</span></label>
              <div className="flex items-center gap-2">
                <select
                  value={manualHour}
                  onChange={(e) => setManualHour(e.target.value)}
                  className="flex-1 px-4 py-3 bg-gray-50 border border-gray-200 rounded-xl focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all text-sm font-medium appearance-none"
                >
                  {Array.from({ length: 12 }).map((_, i) => {
                    const h = (i + 1).toString().padStart(2, '0');
                    return <option key={h} value={h}>{h}</option>;
                  })}
                </select>
                <span className="text-gray-500 font-bold">:</span>
                <select
                  value={manualMinute}
                  onChange={(e) => setManualMinute(e.target.value)}
                  className="flex-1 px-4 py-3 bg-gray-50 border border-gray-200 rounded-xl focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all text-sm font-medium appearance-none"
                >
                  {Array.from({ length: 60 }).map((_, i) => {
                    const m = i.toString().padStart(2, '0');
                    return <option key={m} value={m}>{m}</option>;
                  })}
                </select>
                <select
                  value={manualAmpm}
                  onChange={(e) => setManualAmpm(e.target.value)}
                  className="flex-1 px-4 py-3 bg-gray-50 border border-gray-200 rounded-xl focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all text-sm font-medium appearance-none"
                >
                  <option value="AM">AM</option>
                  <option value="PM">PM</option>
                </select>
              </div>
            </div>
          </div>
          <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
            <div>
              <label className="block text-sm font-bold text-gray-700 mb-2">End Date (Optional)</label>
              <input
                type="date"
                value={manualEndDate}
                min={new Date().toISOString().split('T')[0]}
                onChange={(e) => setManualEndDate(e.target.value)}
                className="w-full px-4 py-3 bg-gray-50 border border-gray-200 rounded-xl focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all text-sm font-medium"
              />
            </div>
          </div>
          
          <button
            onClick={addToGoogleCalendarApi}
            className={`mt-4 w-full md:w-auto px-6 py-3 rounded-xl font-bold text-sm flex items-center justify-center gap-2 transition-all shadow-sm bg-blue-600 hover:bg-blue-700 text-white shadow-blue-200`}
          >
            <ExternalLink className="w-4 h-4" /> Save to Google Calendar
          </button>
        </div>
      </div>
    </div>
  );
}

